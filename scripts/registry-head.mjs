// Writes registry/head.html: the snippet the schema registry (schemas.asyncapi.pavelon.dev) injects into the <head> of
// its explorer pages. It adds a link from each schema to the page that explains it here, so people and crawlers that
// land on a raw schema find the documentation. The registry lowercases paths, so the security pages need a lookup
// table; bindings follow one rule.
//
//   node scripts/registry-head.mjs          write the file
//   node scripts/registry-head.mjs --check  fail if the file is out of date (run by `build`)
import fs from 'node:fs'
import path from 'node:path'

const OUT = 'registry/head.html'
const DOCS = 'src/content/docs'

/** Registry path (lowercase, under /draft-07/schemas/) → docs page, for every security scheme page. */
function securityPages() {
  const root = path.join(DOCS, 'schemas/v3/security')
  const pages = {}
  const walk = (dir) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name)
      if (entry.isDirectory()) walk(file)
      else if (entry.name.endsWith('.md')) {
        const rel = path.relative(path.join(DOCS, 'schemas'), file).replace(/\.md$/, '').split(path.sep).join('/')
        pages[rel.toLowerCase()] = `/schemas/${rel}`
      }
    }
  }
  walk(root)
  return Object.fromEntries(Object.entries(pages).sort())
}

const pages = { schema: '/schemas/schema', multiformatschema: '/schemas/multiFormatSchema', ...securityPages() }

const script = `(function () {
  var DOCS = 'https://asyncapi.pavelon.dev';
  var PAGES = ${JSON.stringify(pages)};
  var p = location.pathname.replace(/\\/+$/, '').replace(/\\.json$/, '').toLowerCase();
  var m, href;
  if ((m = p.match(/^\\/draft-07\\/bindings\\/([^/]+)\\/(\\d+\\.\\d+\\.\\d+)\\/(server|channel|operation|message)$/))) {
    href = '/bindings/' + m[1] + '/' + m[2] + '/' + m[3];
  } else if ((m = p.match(/^\\/draft-07\\/bindings\\/([^/]+)/))) {
    href = '/bindings/' + m[1] + '/';
  } else if (p === '/draft-07/bindings') {
    href = '/bindings/';
  } else if ((m = p.match(/^\\/draft-07\\/schemas\\/(.+)$/)) && PAGES[m[1]]) {
    href = PAGES[m[1]];
  } else {
    href = '/schemas/registry';
  }
  var link = document.createElement('link');
  link.rel = 'help';
  link.href = DOCS + href;
  document.head.appendChild(link);
  document.addEventListener('DOMContentLoaded', function () {
    var a = document.createElement('a');
    a.href = DOCS + href;
    a.textContent = href === '/schemas/registry' ? 'How to use the registry' : 'Read the documentation';
    a.style.cssText = 'position:fixed;right:1rem;bottom:1rem;z-index:1030;padding:.5rem .9rem;border-radius:999px;background:#0d6efd;color:#fff;font:600 14px/1.2 system-ui,sans-serif;text-decoration:none;box-shadow:0 2px 8px rgba(0,0,0,.2)';
    document.body.appendChild(a);
  });
})();`

const html = `<!-- Generated by scripts/registry-head.mjs in asyncapi-bindings-docs. Paste into the registry's <head> setting. -->
<script>
${script}
</script>
`

if (process.argv.includes('--check')) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : ''
  if (current !== html) {
    console.error(`${OUT} is out of date: run \`npm run registry:head\` and commit it.`)
    process.exit(1)
  }
} else {
  fs.mkdirSync(path.dirname(OUT), { recursive: true })
  fs.writeFileSync(OUT, html)
  console.log(`Wrote ${OUT} (${Object.keys(pages).length} schema pages)`)
}
